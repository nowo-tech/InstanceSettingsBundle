<?php

declare(strict_types=1);

namespace Nowo\InstanceSettingsBundle\Embed;

use InvalidArgumentException;
use Nowo\UiKitBundle\View\PageHeader;

use function get_debug_type;
use function in_array;
use function is_string;
use function preg_match;
use function sprintf;

/**
 * How a host page embeds settings sections (1.6, IS-1): which sections its nav shows, the host route of each section
 * (tab links and the redirect after a save), and optional layout, template and header overrides.
 *
 * Every value comes from host code, never from the request. The allowlist only narrows: a listed section the user may
 * not open is still hidden and still denied ({@see SettingsSectionEmbedder}). The redirect target is always a host
 * route name generated by the router, never a URL, so an embed cannot become an open redirect.
 *
 * Immutable and free of services (worker-safe).
 */
final readonly class SectionEmbedOptions
{
    /** Section names accepted in the allowlist (same as the bundle route requirement). */
    public const SECTION_PATTERN = '/^[a-z][a-z0-9_]{0,63}$/';

    /** Route names accepted for the host routes (no slash, no scheme: a route name, never a path or a URL). */
    public const ROUTE_PATTERN = '/^[A-Za-z_][A-Za-z0-9_.\-]{0,199}$/';

    /** @var list<string> */
    public array $sections;

    /**
     * Use {@see self::routes()} (one host route per section) or {@see self::route()} (one host route with a section
     * parameter).
     *
     * @param list<string> $sections section allowlist of the nav, in the bundle's section order
     * @param array<string, string> $routes section => host route name (tab links and the redirect after a save)
     * @param array<string, scalar> $routeParameters parameters added to every host route
     * @param string|null $sectionParameter route parameter that carries the section name (single-route form), or null
     * @param string|null $template page template (null = `web_ui.templates.section`, else the bundle template)
     * @param string|null $layout layout the scaffold extends (null = `web_ui.layout_template`, else UiKit's admin layout)
     * @param PageHeader|null $header page header (null = the bundle's title and intro, without the import / export link)
     * @param array<string, mixed> $context extra template variables (the bundle's variables win on a name clash)
     */
    private function __construct(
        array $sections,
        public array $routes,
        public array $routeParameters = [],
        public ?string $sectionParameter = null,
        public ?string $template = null,
        public ?string $layout = null,
        public ?PageHeader $header = null,
        public array $context = [],
    ) {
        if ($sections === []) {
            throw new InvalidArgumentException('SectionEmbedOptions needs at least one section.');
        }
        $list = [];
        foreach ($sections as $section) {
            if (!is_string($section) || preg_match(self::SECTION_PATTERN, $section) !== 1) {
                throw new InvalidArgumentException(sprintf('Invalid embedded section name "%s".', is_string($section) ? $section : get_debug_type($section)));
            }
            if (!in_array($section, $list, true)) {
                $list[] = $section;
            }
        }
        foreach ($routes as $section => $route) {
            if (!is_string($route) || preg_match(self::ROUTE_PATTERN, $route) !== 1) {
                throw new InvalidArgumentException(sprintf('The host route of the embedded section "%s" must be a route name, not a path or a URL.', $section));
            }
        }
        if ($sectionParameter !== null && preg_match('/^[A-Za-z_][A-Za-z0-9_]{0,63}$/', $sectionParameter) !== 1) {
            throw new InvalidArgumentException(sprintf('Invalid section route parameter "%s".', $sectionParameter));
        }
        foreach ([$template, $layout] as $name) {
            if ($name === '') {
                throw new InvalidArgumentException('SectionEmbedOptions template and layout must not be empty strings (use null for the default).');
            }
        }
        $this->sections = $list;
    }

    /**
     * One host route per section, e.g. `['brand' => 'app_appearance_brand', 'appearance' => 'app_appearance_theme']`.
     * The sections are the keys of `$routes`.
     *
     * @param array<string, string> $routes section => host route name
     * @param array<string, scalar> $routeParameters parameters added to every route
     */
    public static function routes(array $routes, array $routeParameters = []): self
    {
        $sections = [];
        foreach ($routes as $section => $route) {
            $sections[] = (string) $section;
        }

        return new self($sections, $routes, $routeParameters);
    }

    /**
     * One host route for every listed section, the section name in `$sectionParameter`, e.g.
     * `route('app_appearance', ['brand', 'appearance'])` for `/developer/appearance/{section}`.
     *
     * @param list<string> $sections section allowlist
     * @param array<string, scalar> $routeParameters parameters added to the route
     */
    public static function route(string $route, array $sections, string $sectionParameter = 'section', array $routeParameters = []): self
    {
        $routes = [];
        foreach ($sections as $section) {
            if (is_string($section)) {
                $routes[$section] = $route;
            }
        }

        return new self($sections, $routes, $routeParameters, $sectionParameter);
    }

    /**
     * Copy rendered with another page template (it receives the same variables as the bundle section template).
     */
    public function withTemplate(?string $template): self
    {
        return new self($this->sections, $this->routes, $this->routeParameters, $this->sectionParameter, $template, $this->layout, $this->header, $this->context);
    }

    /**
     * Copy whose scaffold extends another layout (the host's own page layout).
     */
    public function withLayout(?string $layout): self
    {
        return new self($this->sections, $this->routes, $this->routeParameters, $this->sectionParameter, $this->template, $layout, $this->header, $this->context);
    }

    /**
     * Copy with the host's page header (title, intro, breadcrumbs, area nav) instead of the bundle's.
     */
    public function withHeader(?PageHeader $header): self
    {
        return new self($this->sections, $this->routes, $this->routeParameters, $this->sectionParameter, $this->template, $this->layout, $header, $this->context);
    }

    /**
     * Copy with extra template variables (the bundle's own variables win on a name clash).
     *
     * @param array<string, mixed> $context
     */
    public function withContext(array $context): self
    {
        return new self($this->sections, $this->routes, $this->routeParameters, $this->sectionParameter, $this->template, $this->layout, $this->header, $context);
    }

    /**
     * Whether the allowlist lists `$section`.
     */
    public function allows(string $section): bool
    {
        return in_array($section, $this->sections, true);
    }

    /**
     * Host route name and parameters of a listed section.
     *
     * @return array{0: string, 1: array<string, scalar>}
     */
    public function routeOf(string $section): array
    {
        if (!$this->allows($section)) {
            throw new InvalidArgumentException(sprintf('The section "%s" is not embedded.', $section));
        }
        $parameters = $this->routeParameters;
        if ($this->sectionParameter !== null) {
            $parameters[$this->sectionParameter] = $section;
        }

        return [$this->routes[$section], $parameters];
    }
}
