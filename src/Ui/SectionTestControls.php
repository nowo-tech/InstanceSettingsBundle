<?php

declare(strict_types=1);

namespace Nowo\InstanceSettingsBundle\Ui;

use Nowo\InstanceSettingsBundle\Embed\SettingsSectionEmbedder;
use Nowo\InstanceSettingsBundle\SectionTest\SectionTestRunner;

/**
 * What `settings/_section_test.html.twig` needs to render the Test buttons of one section (1.18): the endpoint URL, the
 * section's CSRF token id, the section's translation domain and one {@see SectionTestButton} per tester (the section
 * tester and / or one per tested field group).
 *
 * Built by {@see SettingsSectionEmbedder} only when the section has a tester and the user may test it
 * ({@see SectionTestRunner::canTest()}), so a page without a tester carries no test markup at all. It never holds a
 * setting value: the last reports hold translation keys and redacted parameters only.
 */
final readonly class SectionTestControls
{
    /**
     * @param string $section section name
     * @param string $url URL of the test endpoint (generated by the router)
     * @param string $domain translation domain of the section (labels and hints of the checks without their own)
     * @param list<SectionTestButton> $buttons one per tester, the section tester first
     */
    public function __construct(
        public string $section,
        public string $url,
        public string $domain,
        public array $buttons,
    ) {
    }

    /**
     * CSRF token id of the section (the section form's own: {@see SettingsSectionEmbedder::CSRF_TOKEN_PREFIX}).
     */
    public function tokenId(): string
    {
        return SettingsSectionEmbedder::CSRF_TOKEN_PREFIX . $this->section;
    }
}
