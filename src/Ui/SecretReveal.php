<?php

declare(strict_types=1);

namespace Nowo\InstanceSettingsBundle\Ui;

use Nowo\InstanceSettingsBundle\Controller\SettingsController;
use Nowo\InstanceSettingsBundle\Embed\SettingsSectionEmbedder;
use Nowo\InstanceSettingsBundle\Secret\SecretRevealer;

use function json_encode;

use const JSON_FORCE_OBJECT;
use const JSON_THROW_ON_ERROR;
use const JSON_UNESCAPED_SLASHES;
use const JSON_UNESCAPED_UNICODE;

/**
 * What `settings/_secret_reveal.html.twig` needs to render the Reveal control of the revealable secret rows of one
 * section (1.15): the endpoint URL of each field and the CSRF token id of the section.
 *
 * Built by {@see SettingsSectionEmbedder} only for a user who may reveal
 * ({@see SecretRevealer::canReveal()}), so a page without the control carries no reveal markup at all. It never holds a
 * secret: the plaintext is fetched by the script from the endpoint, one field per call, and only lives in the browser
 * from the moment the user clicks Reveal.
 */
final readonly class SecretReveal
{
    /**
     * @param string $section section name
     * @param array<string, string> $urls revealable field name => URL of its reveal endpoint (generated by the router)
     */
    public function __construct(
        public string $section,
        public array $urls,
    ) {
    }

    /**
     * CSRF token id of the section's reveal calls ({@see SettingsController::REVEAL_TOKEN_PREFIX}).
     */
    public function tokenId(): string
    {
        return SettingsController::REVEAL_TOKEN_PREFIX . $this->section;
    }

    /**
     * {@see self::$urls} as JSON, for the script's `data-urls` attribute (field => URL only, no secret).
     */
    public function urlsJson(): string
    {
        return json_encode($this->urls, JSON_FORCE_OBJECT | JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    }
}
