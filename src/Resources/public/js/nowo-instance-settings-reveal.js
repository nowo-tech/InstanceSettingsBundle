/*
 * InstanceSettingsBundle 1.15 — Reveal control of a revealable stored secret (settings/_secret_reveal.html.twig).
 *
 * Plain script (no build, no dependency), loaded deferred with the request CSP nonce by the section page when the user
 * may reveal a revealable secret of the section. Idempotent: loading it twice binds once. Binds by delegation on the
 * document, so rows added later work too; window.NowoInstanceSettingsReveal.init(root) upgrades rows inserted after
 * load.
 *
 * - Every secret row marked data-nowo-instance-settings-reveal="<field>" gets the controls of the page template
 *   (Reveal / Copy / Hide and the output element).
 * - A row belongs to the Reveal root of its own section: its enclosing root, else the root whose data-section equals
 *   the row's data-nowo-instance-settings-reveal-section, else (a single root) the only one there is (audit F3). A page
 *   embedding two sections therefore never shows one section's secret under the other section's label, not even when
 *   both sections declare the same field name.
 * - Reveal POSTs to the endpoint URL of that field (from data-urls of its own root, generated by the router: the
 *   script never builds a path) with that section's CSRF token in the body, and shows the value the server answers.
 *   The value is written with textContent (never innerHTML), is never put in a URL and never logged.
 * - Hide drops it again; it is also dropped automatically after AUTO_HIDE_MS and when the page is hidden (another tab,
 *   minimised window), so a revealed secret does not sit on screen.
 * - Copy uses the asynchronous clipboard; it is skipped silently where the browser refuses it. The clipboard is a
 *   store this page does not own: the operating system may keep and sync its history (Windows Clipboard History,
 *   macOS Universal Clipboard). Hide asks for it to be emptied when this row's Copy was the last one used, but that is
 *   best effort — the browser may refuse, and nothing can reach what the system already synced (audit F4).
 * - 1.16 (web_ui.reveal_on_toggle, data-on-toggle on the root): the PasswordToggle eye of a revealable row
 *   ([data-nowo-password-toggle-target="button"] inside the row) runs the same reveal call instead of unmasking the
 *   typed text: first click (or Enter / Space) reveals, the second hides. The answer goes to the same read-only
 *   <output> as the Reveal button's (it has no name, so it is never part of the submitted form), never into the input,
 *   whose type, value and name are left alone. The eye carries aria-pressed and the "reveal stored value" / "hide"
 *   label; an error or a refusal (rate limit, access) shows the Reveal button's message and the eye returns to its
 *   hidden state. Hiding, the auto-hide delay, the page being hidden and the form being submitted drop the value. With
 *   data-toggle-only the Reveal / Copy / Hide buttons of rows that have the eye stay hidden.
 * - A late answer is dropped when the row was hidden in the meantime (Hide or the eye clicked again before the server
 *   answered), so a value the user already dismissed never appears.
 * - 1.16.1 (audit PK-L1 / I2): leaving the page (pagehide) and Turbo Drive's turbo:before-cache drop every revealed
 *   value, so neither the back / forward cache nor Turbo's page snapshot brings it back. Turbo is not required: the
 *   script only listens for its event. The clipboard is kept, as when the page is hidden (audit N1).
 * - 1.16.1 (audit PK-I8): one call at a time per row. Auto-repeated key presses on the eye (a held Enter) are ignored,
 *   and a click that would reveal while the row's previous call is still waiting for the server does nothing; a click
 *   that hides still hides at once (and that answer is dropped).
 * - 1.16.1 (audit PK-I7): with data-toggle-only there is no Hide button, so an error message goes away on the next eye
 *   click or after MESSAGE_HIDE_MS.
 * - 1.17 (web_ui.reveal_in_input, data-in-input on the root): a row the server marks data-nowo-instance-settings-locked
 *   (a stored revealable secret) is LOCKED: its input is read-only and keeps the "saved" placeholder, so nothing can be
 *   typed. The eye shows the stored value IN that input (type=text) through the same reveal call (endpoint, CSRF token,
 *   limiter, roles, audit, one call at a time) and hides it again; while shown the input carries autocomplete="off",
 *   spellcheck="false", autocapitalize="off", autocorrect="off" and the password-manager opt-outs (data-1p-ignore,
 *   data-lpignore, data-bwignore), all restored on hide. The second click, the auto-hide delay, a hidden page,
 *   pagehide, turbo:before-cache and every submit hide it: type=password, value emptied (switching the type also drops
 *   the editor's undo history, so Ctrl+Z cannot bring the value back). The row's <output> is used for error messages
 *   only, and its Reveal / Copy / Hide buttons stay hidden. The status element announces "shown" / "hidden", never the
 *   value. Ticking the row's "Replace the stored value" box (data-nowo-instance-settings-replace-for, rendered by the
 *   form) unlocks an empty password input, where the eye is PasswordToggle's own again; unticking locks it again. A
 *   locked input never carries a value on submit (the formdata event blanks it, for new FormData(form) too), and the
 *   server ignores one without the Replace box anyway.
 * Without this script nothing is added: the field stays write-only ("leave blank to keep"), as before 1.15.
 */
(function () {
    'use strict';

    if (window.NowoInstanceSettingsReveal) {
        return;
    }

    var ROOT = '[data-nowo-instance-settings-reveal-root]';
    var ROW = '[data-nowo-instance-settings-reveal]';
    var TEMPLATE = '[data-nowo-instance-settings-reveal-template]';
    var SHOW = '[data-nowo-instance-settings-reveal-show]';
    var COPY = '[data-nowo-instance-settings-reveal-copy]';
    var HIDE = '[data-nowo-instance-settings-reveal-hide]';
    var OUTPUT = '[data-nowo-instance-settings-reveal-output]';
    var SECTION = 'data-nowo-instance-settings-reveal-section';
    var DONE = 'data-nowo-instance-settings-reveal-ready';
    var EYE = '[data-nowo-password-toggle-target="button"]';
    var STATUS = '[data-nowo-instance-settings-reveal-status]';
    var LOCKED = 'data-nowo-instance-settings-locked';
    var REPLACE_FOR = 'data-nowo-instance-settings-replace-for';
    var VALUE_INPUT = 'input[name$="[value]"]';
    // 1.17: set on the input while it shows the stored value (restored on hide).
    var MASKING = {
        autocomplete: 'off',
        spellcheck: 'false',
        autocapitalize: 'off',
        autocorrect: 'off',
        'data-1p-ignore': 'true',
        'data-lpignore': 'true',
        'data-bwignore': 'true',
    };
    // 1.17: row => the input's attributes before the stored value was shown in it.
    var shown = new WeakMap();
    // 1.17: eye => its own label / title / pressed state, put back when the row is unlocked for a new value.
    var eyeLabels = new WeakMap();
    var AUTO_HIDE_MS = 60000;
    var MESSAGE_HIDE_MS = 10000;
    var timers = new WeakMap();
    var pending = new WeakMap();
    // Rows whose reveal call is still on the network. Unlike pending, clear() leaves it: a hidden row's call is still out.
    var inFlight = new WeakSet();
    var copied = null;

    // The Reveal root of this row's own section (audit F3): never "the first root of the document".
    function rootOf(row) {
        var scope = row && row.ownerDocument ? row.ownerDocument : document;
        var inside = row && row.closest ? row.closest(ROOT) : null;
        if (inside) {
            return inside;
        }
        var section = row ? row.getAttribute(SECTION) : null;
        var roots = scope.querySelectorAll(ROOT);
        if (section) {
            for (var i = 0; i < roots.length; i++) {
                if (roots[i].getAttribute('data-section') === section) {
                    return roots[i];
                }
            }

            return null;
        }

        return roots.length === 1 ? roots[0] : null;
    }

    function urls(element) {
        try {
            var map = JSON.parse(element.getAttribute('data-urls') || '{}');

            return map && typeof map === 'object' ? map : {};
        } catch (e) {
            return {};
        }
    }

    function label(element, name) {
        return element ? element.getAttribute('data-' + name + '-label') || '' : '';
    }

    function parts(row) {
        return {
            show: row.querySelector(SHOW),
            copy: row.querySelector(COPY),
            hide: row.querySelector(HIDE),
            output: row.querySelector(OUTPUT),
        };
    }

    // 1.16: the PasswordToggle eye of this row, only when its root opted in (web_ui.reveal_on_toggle).
    function eyeOf(row) {
        var element = rootOf(row);
        if (!element || element.getAttribute('data-on-toggle') !== 'true') {
            return null;
        }

        return row.querySelector(EYE);
    }

    // 1.17: a stored secret row of a root with data-in-input (web_ui.reveal_in_input).
    function inInputRow(row) {
        var element = rootOf(row);

        return !!(element && element.getAttribute('data-in-input') === 'true' && row.getAttribute(LOCKED) === 'true');
    }

    function inputOf(row) {
        return row.querySelector(VALUE_INPUT);
    }

    // The row's "Replace the stored value" box, in the row's own form.
    function replaceBox(row) {
        var field = row.getAttribute('data-nowo-instance-settings-reveal') || '';
        var scope = row.closest('form') || row.ownerDocument || document;
        var holders = scope.querySelectorAll('[' + REPLACE_FOR + ']');
        for (var i = 0; i < holders.length; i++) {
            if (holders[i].getAttribute(REPLACE_FOR) === field) {
                return holders[i].querySelector('input[type="checkbox"]');
            }
        }

        return null;
    }

    // Locked: a stored secret, Replace not ticked.
    function isLocked(row) {
        var box = inInputRow(row) ? replaceBox(row) : null;

        return inInputRow(row) && !(box && box.checked);
    }

    // The eye of a locked row shows the stored value in the input itself.
    function usesInput(row) {
        return isLocked(row) && !!eyeOf(row) && !!inputOf(row);
    }

    // 1.16 (web_ui.reveal_toggle_only): a row with the eye keeps its Reveal / Copy / Hide buttons hidden; 1.17: so does a
    // locked row whose eye reveals into the input.
    function buttonsOff(row) {
        var element = rootOf(row);

        return !!(element && element.getAttribute('data-toggle-only') === 'true' && eyeOf(row)) || usesInput(row);
    }

    function announce(row, kind) {
        var status = row.querySelector(STATUS);
        if (status) {
            status.textContent = label(rootOf(row), kind);
        }
    }

    // Shows the stored value in the locked input (1.17).
    function showIn(row, value) {
        var input = inputOf(row);
        var before = {};
        for (var name in MASKING) {
            before[name] = input.hasAttribute(name) ? input.getAttribute(name) : null;
            input.setAttribute(name, MASKING[name]);
        }
        shown.set(row, before);
        input.type = 'text';
        input.value = value;
        announce(row, 'shown');
    }

    // Hides it again: type=password (a new editor: no undo history), empty value, attributes restored.
    function hideIn(row) {
        var before = shown.get(row);
        var input = inputOf(row);
        if (!before || !input) {
            return;
        }
        shown.delete(row);
        input.value = '';
        input.type = 'password';
        input.value = '';
        for (var name in before) {
            if (before[name] === null) {
                input.removeAttribute(name);
            } else {
                input.setAttribute(name, before[name]);
            }
        }
        announce(row, 'hidden');
    }

    function setEye(row, revealed) {
        var eye = eyeOf(row);
        if (!eye || (inInputRow(row) && !isLocked(row))) {
            // 1.17: an unlocked row's eye is PasswordToggle's own.
            return;
        }
        eye.setAttribute('aria-pressed', revealed ? 'true' : 'false');
        var text = label(rootOf(row), revealed ? 'toggle-hide' : 'toggle-show');
        if (text) {
            eye.setAttribute('aria-label', text);
            eye.setAttribute('title', text);
        }
        if (revealed) {
            eye.classList.add('is-password-visible');
        } else {
            eye.classList.remove('is-password-visible');
        }
    }

    // Best effort (audit F4): the page cannot clear what the system already kept or synced.
    function forgetClipboard(row) {
        if (copied !== row || !window.navigator.clipboard) {
            return;
        }
        copied = null;
        try {
            var done = window.navigator.clipboard.writeText('');
            if (done && typeof done.catch === 'function') {
                done.catch(function () {});
            }
        } catch (e) {
            // The browser refused the clipboard: the value stays where the user put it.
        }
    }

    function clear(row, keepClipboard) {
        var p = parts(row);
        // A call still in flight is dropped when it answers (the user already hid the row).
        pending.delete(row);
        hideIn(row);
        setEye(row, false);
        if (!p.output) {
            return;
        }
        p.output.textContent = '';
        p.output.hidden = true;
        if (p.copy) {
            p.copy.hidden = true;
        }
        if (p.hide) {
            p.hide.hidden = true;
        }
        if (p.show) {
            p.show.hidden = buttonsOff(row);
        }
        var timer = timers.get(row);
        if (timer) {
            window.clearTimeout(timer);
            timers.delete(row);
        }
        if (!keepClipboard) {
            forgetClipboard(row);
        }
    }

    function render(row, text, revealed) {
        var p = parts(row);
        if (revealed && usesInput(row)) {
            // 1.17: the stored value goes into the locked input; the <output> is for messages only.
            if (p.output) {
                p.output.textContent = '';
                p.output.hidden = true;
            }
            showIn(row, text);
            setEye(row, true);
            var running = timers.get(row);
            if (running) {
                window.clearTimeout(running);
            }
            timers.set(row, window.setTimeout(function () {
                clear(row);
            }, AUTO_HIDE_MS));

            return;
        }
        if (!p.output) {
            return;
        }
        var off = buttonsOff(row);
        p.output.textContent = text;
        p.output.hidden = false;
        if (p.copy) {
            p.copy.hidden = off || !revealed;
        }
        if (p.hide) {
            p.hide.hidden = off;
        }
        if (p.show) {
            p.show.hidden = true;
        }
        // The eye is "pressed" only while a value is shown: an error or a refusal leaves it in its hidden state.
        setEye(row, revealed);
        var previous = timers.get(row);
        if (previous) {
            window.clearTimeout(previous);
            timers.delete(row);
        }
        if (revealed) {
            timers.set(row, window.setTimeout(function () {
                clear(row);
            }, AUTO_HIDE_MS));
        } else if (off) {
            // No Hide button for the message (audit PK-I7): it goes away by itself.
            timers.set(row, window.setTimeout(function () {
                clear(row, true);
            }, MESSAGE_HIDE_MS));
        }
    }

    function reveal(row) {
        var element = rootOf(row);
        var field = row.getAttribute('data-nowo-instance-settings-reveal');
        var url = element ? urls(element)[field] : null;
        if (!element || !url) {
            setEye(row, false);

            return;
        }
        // One call at a time per row (audit PK-I8): the server answers the one already out.
        if (inFlight.has(row)) {
            return;
        }
        var call = {};
        pending.set(row, call);
        inFlight.add(row);
        var body = new URLSearchParams();
        body.set('_token', element.getAttribute('data-token') || '');
        window.fetch(url, {
            method: 'POST',
            credentials: 'same-origin',
            cache: 'no-store',
            headers: { 'Content-Type': 'application/x-www-form-urlencoded', 'X-Requested-With': 'XMLHttpRequest' },
            body: body.toString(),
        }).then(function (response) {
            inFlight.delete(row);

            return response.json().then(function (payload) {
                return { ok: response.ok, payload: payload };
            });
        }).then(function (result) {
            if (pending.get(row) !== call) {
                return;
            }
            pending.delete(row);
            if (result.ok && typeof result.payload.value === 'string') {
                render(row, result.payload.value, true);

                return;
            }
            render(row, label(element, result.payload && result.payload.error === 'not_stored' ? 'empty' : 'error'), false);
        }).catch(function () {
            inFlight.delete(row);
            if (pending.get(row) !== call) {
                return;
            }
            pending.delete(row);
            render(row, label(element, 'error'), false);
        });
    }

    function copy(row) {
        var p = parts(row);
        if (!p.output || !p.copy || !window.navigator.clipboard) {
            return;
        }
        var done = label(rootOf(row), 'copied');
        window.navigator.clipboard.writeText(p.output.textContent).then(function () {
            copied = row;
            if (done) {
                p.copy.textContent = done;
            }
        }).catch(function () {
            // The browser refused the clipboard (no permission, no secure context): leave the value on screen.
        });
    }

    // Upgrades every marked row in scope, each from the template of its own section's root (audit F3).
    function init(scope) {
        var where = scope && scope.querySelectorAll ? scope : document;
        var rows = where.querySelectorAll(ROW);
        for (var i = 0; i < rows.length; i++) {
            var row = rows[i];
            if (row.hasAttribute(DONE)) {
                continue;
            }
            var element = rootOf(row);
            var template = element ? element.querySelector(TEMPLATE) : null;
            if (!template) {
                continue;
            }
            row.setAttribute(DONE, '');
            row.appendChild(template.content.cloneNode(true));
            var own = eyeOf(row);
            if (own && !eyeLabels.has(own)) {
                eyeLabels.set(own, { label: own.getAttribute('aria-label'), title: own.getAttribute('title'), pressed: own.getAttribute('aria-pressed') });
            }
            if (inInputRow(row)) {
                // 1.17: locked unless the page came back with Replace ticked (a refused save).
                setLocked(row, isLocked(row));
            }
            if (eyeOf(row)) {
                setEye(row, false);
                var show = row.querySelector(SHOW);
                if (show) {
                    show.hidden = buttonsOff(row);
                }
            }
        }
    }

    function restoreAttribute(element, name, value) {
        if (value === null || value === undefined) {
            element.removeAttribute(name);
        } else {
            element.setAttribute(name, value);
        }
    }

    // 1.17: locks (read-only, empty) or unlocks (an empty password input to type a new value) a stored secret row.
    function setLocked(row, locked) {
        clear(row, true);
        var input = inputOf(row);
        if (!input) {
            return;
        }
        input.type = 'password';
        input.value = '';
        input.readOnly = locked;
        var eye = eyeOf(row);
        var own = eye ? eyeLabels.get(eye) : null;
        if (locked) {
            setEye(row, false);
        } else if (eye && own) {
            restoreAttribute(eye, 'aria-label', own.label);
            restoreAttribute(eye, 'title', own.title);
            restoreAttribute(eye, 'aria-pressed', own.pressed);
            eye.classList.remove('is-password-visible');
        }
        var p = parts(row);
        if (p.show) {
            p.show.hidden = buttonsOff(row);
        }
    }

    // 1.17: the Replace box of a locked row unlocks it (ticked) or locks it again (unticked).
    function onChange(event) {
        var box = event.target instanceof HTMLInputElement && event.target.type === 'checkbox' ? event.target : null;
        var holder = box ? box.closest('[' + REPLACE_FOR + ']') : null;
        if (!holder) {
            return;
        }
        var scope = box.form || document;
        var rows = scope.querySelectorAll(ROW);
        for (var i = 0; i < rows.length; i++) {
            if (rows[i].getAttribute('data-nowo-instance-settings-reveal') === holder.getAttribute(REPLACE_FOR) && inInputRow(rows[i])) {
                setLocked(rows[i], !box.checked);
                if (box.checked && inputOf(rows[i])) {
                    inputOf(rows[i]).focus();
                }
            }
        }
    }

    // 1.16: the eye of an opted-in revealable row reveals / hides the stored value. Capture phase on the document, so
    // the PasswordToggle handler (on its host, or Stimulus on the button) never unmasks the input in this mode.
    function onEye(event) {
        var target = event.target instanceof Element ? event.target : null;
        var eye = target ? target.closest(EYE) : null;
        var row = eye ? eye.closest(ROW) : null;
        if (!row || eyeOf(row) !== eye || (inInputRow(row) && !isLocked(row))) {
            // 1.17: an unlocked row (Replace ticked) keeps PasswordToggle's own eye for the typed value.
            return;
        }
        if (event.type === 'keydown' && event.key !== 'Enter' && event.key !== ' ') {
            return;
        }
        event.preventDefault();
        event.stopPropagation();
        // A held key (audit PK-I8): kept from PasswordToggle too, so it never unmasks the input.
        if (event.type === 'keydown' && event.repeat) {
            return;
        }
        if (eye.getAttribute('aria-pressed') === 'true') {
            clear(row);

            return;
        }
        if (inFlight.has(row)) {
            return;
        }
        // Drops a message still on screen (audit PK-I7) before the new call.
        clear(row, true);
        setEye(row, true);
        reveal(row);
    }

    // A submitted form drops the values revealed in its rows (they are not form fields; this keeps them out of the
    // back / forward cache snapshot too).
    function onSubmit(event) {
        var form = event.target instanceof HTMLFormElement ? event.target : null;
        if (!form) {
            return;
        }
        var rows = form.querySelectorAll(ROW);
        for (var i = 0; i < rows.length; i++) {
            clear(rows[i], true);
            // 1.17: a locked input never carries a value (the server ignores one without Replace anyway).
            var input = inputOf(rows[i]);
            if (input && isLocked(rows[i])) {
                input.type = 'password';
                input.value = '';
            }
        }
    }

    // 1.17: the form data set of a form (its submission, or a script's new FormData(form)) never holds a stored value
    // shown in a locked input, nor any value of a locked input.
    function onFormData(event) {
        var form = event.target instanceof HTMLFormElement ? event.target : null;
        if (!form || !event.formData) {
            return;
        }
        var rows = form.querySelectorAll(ROW);
        for (var i = 0; i < rows.length; i++) {
            var input = inputOf(rows[i]);
            if (input && input.name && (shown.has(rows[i]) || isLocked(rows[i]))) {
                event.formData.set(input.name, '');
            }
        }
    }

    function onClick(event) {
        var target = event.target instanceof Element ? event.target : null;
        var row = target ? target.closest(ROW) : null;
        if (!row) {
            return;
        }
        if (target.closest(SHOW)) {
            if (!inFlight.has(row)) {
                reveal(row);
            }
        } else if (target.closest(HIDE)) {
            clear(row);
        } else if (target.closest(COPY)) {
            copy(row);
        }
    }

    // Audit N1: the admin may be switching away to paste, so the clipboard is kept.
    function clearAll() {
        var rows = document.querySelectorAll(ROW);
        for (var i = 0; i < rows.length; i++) {
            clear(rows[i], true);
        }
    }

    function onVisibilityChange() {
        if (document.visibilityState === 'hidden') {
            clearAll();
        }
    }

    document.addEventListener('click', onEye, true);
    document.addEventListener('keydown', onEye, true);
    document.addEventListener('submit', onSubmit, true);
    document.addEventListener('click', onClick);
    document.addEventListener('change', onChange);
    document.addEventListener('formdata', onFormData, true);
    document.addEventListener('visibilitychange', onVisibilityChange);
    // Audit PK-L1 / I2: never in the back / forward cache, nor in Turbo Drive's page snapshot (no Turbo dependency).
    window.addEventListener('pagehide', clearAll);
    document.addEventListener('turbo:before-cache', clearAll);
    document.addEventListener('turbo:load', function () {
        init(document);
    });

    window.NowoInstanceSettingsReveal = { init: init, clear: clear };

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', function () {
            init(document);
        });
    } else {
        init(document);
    }
})();
